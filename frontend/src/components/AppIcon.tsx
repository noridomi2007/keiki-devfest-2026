interface AppIconProps {
  name: string;
  className?: string;
}

/** Bundled vector icon component replacing external Material Symbols webfont ligatures. */
export function AppIcon({ name, className }: AppIconProps) {
  const Component = ICON_MAP[name] || Sparkles;
  const isSpinning = name === 'pending';
  return (
    <Component
      aria-hidden={true}
      className={cn(
        'inline-block size-[1.125em] shrink-0 align-middle',
        isSpinning && 'animate-spin',
        className,
      )}
    />
  );
}
